@app.post("/students/{student_id}/assessments/submit", tags=["Student Portal"])
def submit_assessment(student_id: int, payload: dict[str, Any], db: Session = Depends(get_db)):
    if not db.get(Student, student_id):
        raise HTTPException(404, "Student not found")
    category = str(payload.get("category", "")).strip().lower()
    try:
        score = float(payload.get("score", 0))
        total = int(payload.get("total", 0))
    except (TypeError, ValueError):
        raise HTTPException(422, "Invalid score or total")
    if total <= 0 or score < 0 or score > total:
        raise HTTPException(422, "Invalid score or total")
    names = {"python":"Python Programming","sql":"SQL & Databases","ml":"Machine Learning","aptitude":"Quantitative Aptitude","comm":"Communication Skills"}
    skill_name = names.get(category, category.title())
    if not skill_name:
        raise HTTPException(422, "category is required")
    skill = db.query(Skill).filter(Skill.name.ilike(skill_name)).first()
    if not skill:
        skill = Skill(name=skill_name); db.add(skill); db.flush()
    pct = round(score / total * 100, 2)
    proficiency = "Beginner" if pct < 50 else "Intermediate" if pct < 75 else "Advanced"
    ss = db.query(StudentSkill).filter(StudentSkill.student_id == student_id, StudentSkill.skill_id == skill.id).first()
    if not ss:
        ss = StudentSkill(student_id=student_id, skill_id=skill.id); db.add(ss)
    ss.proficiency = proficiency
    assessment = db.query(Assessment).filter(Assessment.skill_id == skill.id).first()
    if not assessment:
        assessment = Assessment(title=f"{skill_name} Assessment", skill_id=skill.id, total_marks=total, passing_marks=max(1, round(total * .5)))
        db.add(assessment); db.flush()
    attempt = AssessmentAttempt(student_id=student_id, assessment_id=assessment.id, score=score, total_marks=total, percentage=pct, status="passed" if pct >= 50 else "needs_improvement")
    db.add(attempt)
    for gap in db.query(SkillGap).filter(SkillGap.student_id == student_id, SkillGap.missing_skill_id == skill.id).all():
        db.delete(gap)
    if pct < 70:
        db.add(SkillGap(student_id=student_id, missing_skill_id=skill.id, severity="high" if pct < 50 else "medium"))
    db.commit(); db.refresh(attempt)
    return {"attempt_id": attempt.id, "percentage": pct, "proficiency": proficiency}


