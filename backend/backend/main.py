def _skill_names(db: Session, internship_id: int) -> list[str]:
    rows = (db.query(Skill.name)
            .join(InternshipSkill, InternshipSkill.skill_id == Skill.id)
            .filter(InternshipSkill.internship_id == internship_id)
            .order_by(Skill.name)
            .all())
    return [r[0] for r in rows]


def _latest_student_scores(db: Session, student_id: int) -> dict[int, float]:
    attempts = (db.query(AssessmentAttempt)
                .filter(AssessmentAttempt.student_id == student_id)
                .order_by(AssessmentAttempt.attempted_at.desc(), AssessmentAttempt.id.desc())
                .all())
    result: dict[int, float] = {}
    for a in attempts:
        assessment = db.get(Assessment, a.assessment_id)
        if assessment and assessment.skill_id not in result:
            result[assessment.skill_id] = float(a.percentage or 0)
    return result


def _match_for_application(db: Session, application: Application) -> dict[str, Any]:
    skill_rows = (db.query(Skill)
                  .join(InternshipSkill, InternshipSkill.skill_id == Skill.id)
                  .filter(InternshipSkill.internship_id == application.internship_id)
                  .order_by(Skill.name).all())
    scores = _latest_student_scores(db, application.student_id)
    matched, missing, values = [], [], []
    for skill in skill_rows:
        score = scores.get(skill.id, 0)
        if score > 0:
            matched.append(skill.name)
            values.append(score)
        else:
            missing.append(skill.name)
    match_score = round(sum(values) / len(skill_rows), 1) if skill_rows else 0
    student = db.get(Student, application.student_id)
    internship = db.get(Internship, application.internship_id)
    return {
        **serialize(application),
        "student": serialize(student) if student else None,
        "internship": {"id": internship.id, "title": internship.title} if internship else None,
        "match_score": match_score,
        "matched_skills": matched,
        "missing_skills": missing,
    }


def _company_or_404(db: Session, company_id: int) -> Company:
    company = db.get(Company, company_id)
    if not company:
        raise HTTPException(404, "Company not found")
    return company


