@app.post("/companies/{company_id}/internships", status_code=201, tags=["Industry"])
def create_company_internship(company_id: int, payload: dict[str, Any], db: Session = Depends(get_db)):
    _company_or_404(db, company_id)
    title = str(payload.get("title", "")).strip()
    skills = [str(s).strip() for s in payload.get("required_skills", []) if str(s).strip()]
    if not title or not skills:
        raise HTTPException(422, "title and required_skills are required")
    deadline = payload.get("deadline")
    if isinstance(deadline, str) and deadline:
        try:
            deadline = datetime.fromisoformat(deadline.replace("Z", "+00:00"))
        except ValueError:
            raise HTTPException(422, "Invalid deadline")
    obj = Internship(company_id=company_id, title=title, description=payload.get("description"), location=payload.get("location"), duration=payload.get("duration"), stipend=payload.get("stipend"), mode=payload.get("mode"), deadline=deadline, status=payload.get("status") or "open")
    db.add(obj)
    db.flush()
    for name in skills:
        skill = db.query(Skill).filter(Skill.name.ilike(name)).first()
        if not skill:
            skill = Skill(name=name)
            db.add(skill); db.flush()
        if not db.query(InternshipSkill).filter(InternshipSkill.internship_id == obj.id, InternshipSkill.skill_id == skill.id).first():
            db.add(InternshipSkill(internship_id=obj.id, skill_id=skill.id))
    db.commit(); db.refresh(obj)
    data = serialize(obj); data["skills"] = _skill_names(db, obj.id); data["application_count"] = 0
    return data


@app.patch("/companies/{company_id}/internships/{internship_id}", tags=["Industry"])
def update_company_internship(company_id: int, internship_id: int, payload: dict[str, Any], db: Session = Depends(get_db)):
    _company_or_404(db, company_id)
    obj = db.query(Internship).filter(Internship.id == internship_id, Internship.company_id == company_id).first()
    if not obj: raise HTTPException(404, "Internship not found")
    allowed = {"title","description","location","duration","stipend","mode","status"}
    unknown = set(payload) - allowed
    if unknown: raise HTTPException(422, {"message":"Unknown fields", "fields":sorted(unknown)})
    if "status" in payload and payload["status"] not in {"open","closed"}: raise HTTPException(422,"status must be open or closed")
    for k,v in payload.items(): setattr(obj,k,v)
    db.commit(); db.refresh(obj)
    data=serialize(obj); data["skills"]=_skill_names(db,obj.id); data["application_count"]=db.query(Application).filter(Application.internship_id==obj.id).count(); return data


