def _json_value(value: Any) -> Any:
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    return value


def serialize(model: Any) -> dict[str, Any]:
    mapper = inspect(model.__class__)
    return {
        column.key: _json_value(getattr(model, column.key))
        for column in mapper.columns
    }


def serialize_many(rows: list[Any]) -> list[dict[str, Any]]:
    return [serialize(row) for row in rows]


def model_columns(model: Any) -> set[str]:
    return {column.key for column in inspect(model).columns}


def clean_payload(model: Any, payload: dict[str, Any], *, partial: bool = False) -> dict[str, Any]:
    allowed = model_columns(model)
    unknown = sorted(set(payload) - allowed)
    if unknown:
        raise HTTPException(
            status_code=422,
            detail={"message": "Unknown fields", "fields": unknown},
        )
    if not partial:
        # id and server timestamps are generated by the database.
        payload.pop("id", None)
        payload.pop("created_at", None)
        payload.pop("posted_at", None)
        payload.pop("uploaded_at", None)
        payload.pop("generated_at", None)
        payload.pop("attempted_at", None)
        payload.pop("applied_at", None)
        payload.pop("enrolled_at", None)
    return payload


def db_error(exc: IntegrityError) -> HTTPException:
    return HTTPException(
        status_code=400,
        detail="Database constraint failed. Check required fields, unique values, and foreign-key IDs.",
    )


