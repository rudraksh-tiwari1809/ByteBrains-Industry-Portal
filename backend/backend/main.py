# PBKDF2 is used so the backend does not depend on bcrypt/passlib just to boot.
# Passwords are never returned by API responses.
def hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, 310_000)
    return f"pbkdf2_sha256$310000${salt.hex()}${digest.hex()}"


def verify_password(password: str, encoded: str) -> bool:
    try:
        algorithm, rounds, salt_hex, digest_hex = encoded.split("$", 3)
        if algorithm != "pbkdf2_sha256":
            return False
        candidate = hashlib.pbkdf2_hmac(
            "sha256", password.encode(), bytes.fromhex(salt_hex), int(rounds)
        ).hex()
        return hmac.compare_digest(candidate, digest_hex)
    except (ValueError, TypeError):
        return False


def public_user(model: Any) -> dict[str, Any]:
    data = serialize(model)
    data.pop("password_hash", None)
    return data


class AuthRouter:
    def __init__(self, model: Any, prefix: str, label: str):
        self.model = model
        self.router = APIRouter(prefix=prefix, tags=[label])
        self._register()

    def _register(self):
        model = self.model
        router = self.router

        @router.post("/register", status_code=status.HTTP_201_CREATED)
        def register(payload: dict[str, Any], db: Session = Depends(get_db)):
            data = dict(payload)
            password = data.pop("password", None)
            if not password:
                raise HTTPException(422, "password is required")
            if "password_hash" in data:
                data.pop("password_hash")
            data["password_hash"] = hash_password(str(password))
            clean_payload(model, data)
            obj = model(**data)
            db.add(obj)
            try:
                db.commit()
                db.refresh(obj)
            except IntegrityError as exc:
                db.rollback()
                raise db_error(exc)
            return public_user(obj)

        @router.post("/login")
        def login(payload: dict[str, Any], db: Session = Depends(get_db)):
            email = payload.get("email")
            password = payload.get("password")
            if not email or not password:
                raise HTTPException(422, "email and password are required")
            obj = db.query(model).filter(model.email == str(email).strip().lower()).first()
            if not obj or not verify_password(str(password), obj.password_hash):
                raise HTTPException(401, "Invalid email or password")
            return {"authenticated": True, "user": public_user(obj)}


