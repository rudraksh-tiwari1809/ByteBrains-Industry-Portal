# Comma-separated frontend origins can be supplied in backend/.env.
def _cors_origins() -> list[str]:
    raw = os.getenv("CORS_ORIGINS", "*").strip()
    return [x.strip() for x in raw.split(",") if x.strip()] or ["*"]

