def register_crud(resource: str, model: Any) -> None:
    router = APIRouter(prefix=f"/api/{resource}", tags=[resource])
    columns = model_columns(model)

    @router.get("")
    def list_items(
        limit: int = Query(50, ge=1, le=200),
        offset: int = Query(0, ge=0),
        db: Session = Depends(get_db),
    ):
        rows = db.query(model).offset(offset).limit(limit).all()
        return {"items": serialize_many(rows), "count": len(rows), "limit": limit, "offset": offset}

    @router.get("/{item_id}")
    def get_item(item_id: int, db: Session = Depends(get_db)):
        obj = db.get(model, item_id)
        if obj is None:
            raise HTTPException(404, f"{resource[:-1].capitalize()} not found")
        return serialize(obj)

    @router.post("", status_code=status.HTTP_201_CREATED)
    def create_item(payload: dict[str, Any], db: Session = Depends(get_db)):
        data = clean_payload(model, dict(payload))
        # Passwords should be supplied through /auth/*/register.
        if "password_hash" in columns and "password" in data:
            data["password_hash"] = hash_password(str(data.pop("password")))
        obj = model(**data)
        db.add(obj)
        try:
            db.commit()
            db.refresh(obj)
        except IntegrityError as exc:
            db.rollback()
            raise db_error(exc)
        return public_user(obj) if "password_hash" in columns else serialize(obj)

    @router.patch("/{item_id}")
    def update_item(item_id: int, payload: dict[str, Any], db: Session = Depends(get_db)):
        obj = db.get(model, item_id)
        if obj is None:
            raise HTTPException(404, f"{resource[:-1].capitalize()} not found")
        data = clean_payload(model, dict(payload), partial=True)
        data.pop("id", None)
        for key, value in data.items():
            if key in {"password_hash"}:
                continue
            setattr(obj, key, value)
        db.add(obj)
        try:
            db.commit()
            db.refresh(obj)
        except IntegrityError as exc:
            db.rollback()
            raise db_error(exc)
        return public_user(obj) if "password_hash" in columns else serialize(obj)

    @router.delete("/{item_id}")
    def delete_item(item_id: int, db: Session = Depends(get_db)):
        obj = db.get(model, item_id)
        if obj is None:
            raise HTTPException(404, f"{resource[:-1].capitalize()} not found")
        db.delete(obj)
        try:
            db.commit()
        except IntegrityError as exc:
            db.rollback()
            raise db_error(exc)
        return {"deleted": True, "id": item_id}

    app.include_router(router)


for _resource, _model in RESOURCES.items():
    register_crud(_resource, _model)


